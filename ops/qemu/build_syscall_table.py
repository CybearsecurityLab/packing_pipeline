#!/usr/bin/env python3
"""Generate the tracer's Windows service-number table from guest DLL stubs."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import pefile

STUB_PREFIX = b"\x4c\x8b\xd1\xb8"
DEFAULT_DLLS = (
    Path("/data/determinism/vmarm/guestdlls/System32/ntdll.dll"),
    Path("/data/determinism/vmarm/guestdlls/System32/win32u.dll"),
)


def stub_services(image: bytes) -> dict[int, str]:
    pe = pefile.PE(data=image, fast_load=True)
    if pe.FILE_HEADER.Machine != pefile.MACHINE_TYPE["IMAGE_FILE_MACHINE_AMD64"]:
        raise ValueError("expected an x64 image")
    pe.parse_data_directories(
        directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]]
    )
    services: dict[int, str] = {}
    for symbol in getattr(pe, "DIRECTORY_ENTRY_EXPORT").symbols:
        if not symbol.name or symbol.address is None:
            continue
        name = symbol.name.decode("ascii")
        if not name.startswith("Nt") or name.startswith("Ntdll"):
            continue
        try:
            stub = pe.get_data(symbol.address, 8)
        except pefile.PEFormatError:
            continue
        if len(stub) < 8 or stub[:4] != STUB_PREFIX:
            continue
        number = int.from_bytes(stub[4:8], "little")
        previous = services.get(number)
        if previous is not None and previous != name:
            raise ValueError(
                f"service 0x{number:x} maps to both {previous} and {name}"
            )
        services[number] = name
    return services


def render(dlls: list[tuple[str, str, dict[int, str]]]) -> str:
    merged: dict[int, str] = {}
    for label, _, services in dlls:
        for number, name in services.items():
            if number in merged and merged[number] != name:
                raise ValueError(f"{label}: service 0x{number:x} conflicts")
            merged[number] = name
    lines = [
        "/* Generated by ops/qemu/build_syscall_table.py; do not edit. */",
        "#ifndef PAPER_TRACE_SYSCALL_TABLE_H",
        "#define PAPER_TRACE_SYSCALL_TABLE_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for label, digest, services in dlls:
        lines.append(f"#define SYSCALL_TABLE_{label.upper()}_SHA256 \"{digest}\"")
        lines.append(f"#define SYSCALL_TABLE_{label.upper()}_COUNT {len(services)}")
    lines += [
        "",
        "typedef struct {",
        "    uint32_t number;",
        "    const char *name;",
        "} SyscallTableEntry;",
        "",
        "static const SyscallTableEntry syscall_table[] = {",
    ]
    for number in sorted(merged):
        lines.append(f"    {{0x{number:04x}, \"{merged[number]}\"}},")
    lines += [
        "};",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def build(paths: list[Path]) -> str:
    dlls = []
    for path in paths:
        image = path.read_bytes()
        label = path.stem.lower()
        services = stub_services(image)
        if not services:
            raise ValueError(f"{path}: no syscall stubs found")
        dlls.append((label, hashlib.sha256(image).hexdigest(), services))
    return render(dlls)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("dlls", type=Path, nargs="*", default=list(DEFAULT_DLLS))
    args = parser.parse_args()
    text = build(args.dlls)
    temporary = args.output.with_suffix(args.output.suffix + ".tmp")
    temporary.write_text(text)
    temporary.replace(args.output)


if __name__ == "__main__":
    main()
